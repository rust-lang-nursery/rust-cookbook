//! Generates `theme/search-index.js`: crates, topics and recipes extracted from the section
//! tables in `src/*.md`, plus a precomputed menu for every 3-character prefix so the book's
//! search box can show suggestions instantly.

use crate::project_root;
use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::{error::Error, fs};

const SKIPPED_PAGES: &[&str] = &["SUMMARY", "about", "intro", "links"];
const MENU_SIZE: usize = 8;
const PREFIX_LEN: usize = 3;

struct Section {
    title: String,
    url: String,
    aliases: BTreeSet<String>,
}

struct Recipe {
    title: String,
    url: String,
    section: usize,
    crates: Vec<usize>,
}

pub fn run_search_index(check: bool) -> Result<(), Box<dyn Error>> {
    let output = generate()?;
    let path = project_root().join("theme").join("search-index.js");

    if check {
        if fs::read_to_string(&path).ok().as_deref() != Some(output.as_str()) {
            return Err(
                "theme/search-index.js is out of date; run `cargo xtask search-index`".into(),
            );
        }
    } else {
        fs::write(&path, output)?;
    }
    Ok(())
}

fn generate() -> Result<String, Box<dyn Error>> {
    let src = project_root().join("src");
    let mut pages = Vec::new();
    let mut link_sources = Vec::new();
    for entry in fs::read_dir(&src)? {
        let path = entry?.path();
        let stem = path.file_stem().and_then(|s| s.to_str()).unwrap_or("");
        if path.extension().is_some_and(|e| e == "md") {
            let text = fs::read_to_string(&path)?;
            if !SKIPPED_PAGES.contains(&stem) {
                pages.push((stem.to_string(), text.clone()));
            }
            link_sources.push(text);
        }
    }
    pages.sort();

    let mut links = HashMap::new();
    for text in &link_sources {
        for line in text.lines() {
            if let Some((label, url)) = parse_link_definition(line) {
                links.insert(label, url);
            }
        }
    }

    let mut sections = Vec::new();
    let mut crates: BTreeMap<String, usize> = BTreeMap::new();
    let mut recipes = Vec::new();

    for (stem, text) in &pages {
        let Some(title) = text.lines().next().and_then(|l| l.strip_prefix("# ")) else {
            continue;
        };
        let section = sections.len();
        let mut aliases = BTreeSet::new();
        let first_recipe = recipes.len();

        for line in text.lines().filter(|l| l.starts_with("| [")) {
            let cols: Vec<&str> = line.trim_matches('|').split('|').collect();
            let Some((recipe_title, label)) = parse_link(cols[0].trim()) else {
                continue;
            };
            let Some(url) = links.get(&label) else {
                continue;
            };
            let mut recipe_crates = Vec::new();
            for badge in cols.iter().skip(1).flat_map(|c| badges(c)) {
                if let Some(category) = badge.strip_prefix("cat-") {
                    aliases.insert(category.replace('-', " "));
                } else {
                    let name = crate_name(&links, &badge);
                    let next = crates.len();
                    recipe_crates.push(*crates.entry(name).or_insert(next));
                }
            }
            recipes.push(Recipe {
                title: recipe_title,
                url: url.clone(),
                section,
                crates: recipe_crates,
            });
        }
        if recipes.len() > first_recipe {
            sections.push(Section {
                title: title.to_string(),
                url: format!("{stem}.html"),
                aliases,
            });
        }
    }

    // Crates are numbered in discovery order; renumber alphabetically for stable output.
    let names: Vec<String> = crates.keys().cloned().collect();
    let remap: HashMap<usize, usize> = names
        .iter()
        .enumerate()
        .map(|(new, name)| (crates[name], new))
        .collect();
    for recipe in &mut recipes {
        recipe.crates = recipe.crates.iter().map(|c| remap[c]).collect();
        recipe.crates.sort();
        recipe.crates.dedup();
    }

    let prefixes = build_prefixes(&names, &sections, &recipes);

    let mut out = String::from("// Generated by `cargo xtask search-index`. Do not edit.\n");
    out.push_str("window.COOKBOOK_INDEX = {\n");
    out.push_str(&format!("  \"crates\": {},\n", json_strings(names.iter())));
    out.push_str("  \"sections\": [\n");
    let rows: Vec<String> = sections
        .iter()
        .map(|s| {
            format!(
                "    [{}, {}, {}]",
                json_str(&s.title),
                json_str(&s.url),
                json_strings(s.aliases.iter())
            )
        })
        .collect();
    out.push_str(&rows.join(",\n"));
    out.push_str("\n  ],\n  \"recipes\": [\n");
    let rows: Vec<String> = recipes
        .iter()
        .map(|r| {
            let ids: Vec<String> = r.crates.iter().map(|c| c.to_string()).collect();
            format!(
                "    [{}, {}, {}, [{}]]",
                json_str(&r.title),
                json_str(&r.url),
                r.section,
                ids.join(",")
            )
        })
        .collect();
    out.push_str(&rows.join(",\n"));
    out.push_str("\n  ],\n  \"prefixes\": {\n");
    let rows: Vec<String> = prefixes
        .iter()
        .map(|(prefix, menu)| format!("    {}: {}", json_str(prefix), json_strings(menu.iter())))
        .collect();
    out.push_str(&rows.join(",\n"));
    out.push_str("\n  }\n};\n");
    Ok(out)
}

/// For every 3-character prefix of a searchable word, the best few results. Entries are
/// `c<crate>`, `s<section>` or `r<recipe>`; crates rank above topics above recipes.
fn build_prefixes(
    names: &[String],
    sections: &[Section],
    recipes: &[Recipe],
) -> BTreeMap<String, Vec<String>> {
    let mut usage = vec![0usize; names.len()];
    for recipe in recipes {
        for &c in &recipe.crates {
            usage[c] += 1;
        }
    }

    // (rank, tie-break, entry); lower sorts first
    let mut candidates: BTreeMap<String, BTreeMap<String, (usize, usize)>> = BTreeMap::new();
    let mut add = |text: &str, entry: String, rank: usize, tie: usize| {
        let lower = text.to_lowercase();
        let mut keys: BTreeSet<&str> = BTreeSet::new();
        keys.insert(lower.as_str());
        keys.extend(lower.split(|c: char| !c.is_alphanumeric()));
        for key in keys {
            let chars: Vec<char> = key.chars().collect();
            if chars.len() < PREFIX_LEN {
                continue;
            }
            let prefix: String = chars[..PREFIX_LEN].iter().collect();
            let slot = candidates.entry(prefix).or_default();
            let best = slot.entry(entry.clone()).or_insert((rank, tie));
            *best = (*best).min((rank, tie));
        }
    };

    for (i, name) in names.iter().enumerate() {
        add(name, format!("c{i}"), 0, usize::MAX - usage[i]);
    }
    for (i, section) in sections.iter().enumerate() {
        add(&section.title, format!("s{i}"), 1, i);
        for alias in &section.aliases {
            add(alias, format!("s{i}"), 1, i);
        }
    }
    for (i, recipe) in recipes.iter().enumerate() {
        add(&recipe.title, format!("r{i}"), 2, i);
    }

    candidates
        .into_iter()
        .map(|(prefix, entries)| {
            let mut ranked: Vec<_> = entries.into_iter().collect();
            ranked.sort_by_key(|(entry, key)| (*key, entry.clone()));
            let menu = ranked.into_iter().take(MENU_SIZE).map(|(e, _)| e).collect();
            (prefix, menu)
        })
        .collect()
}

/// `[label]: url`
fn parse_link_definition(line: &str) -> Option<(String, String)> {
    let rest = line.strip_prefix('[')?;
    let (label, url) = rest.split_once("]: ")?;
    Some((label.to_string(), url.trim().to_string()))
}

/// `[text][label]`
fn parse_link(cell: &str) -> Option<(String, String)> {
    let rest = cell.strip_prefix('[')?;
    let (text, rest) = rest.split_once("][")?;
    let label = rest.strip_suffix(']')?;
    Some((text.to_string(), label.to_string()))
}

/// The real crate name behind a badge label (`serde-json` is `serde_json`), read from the
/// badge's `img.shields.io/crates/v/<name>.svg` URL.
fn crate_name(links: &HashMap<String, String>, label: &str) -> String {
    links
        .get(&format!("{label}-badge"))
        .and_then(|url| url.split_once("/crates/v/"))
        .and_then(|(_, rest)| rest.split_once(".svg"))
        .map(|(name, _)| name.to_string())
        .unwrap_or_else(|| label.to_string())
}

/// Names `x` from every `[![x-badge]]` in a table cell.
fn badges(cell: &str) -> Vec<String> {
    cell.split("[![")
        .skip(1)
        .filter_map(|part| part.split_once("-badge]").map(|(name, _)| name.to_string()))
        .collect()
}

fn json_strings<'a>(items: impl Iterator<Item = &'a String>) -> String {
    let items: Vec<String> = items.map(|s| json_str(s)).collect();
    format!("[{}]", items.join(", "))
}

fn json_str(s: &str) -> String {
    let mut out = String::from('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
